// Writer extensions used by the SQL Server (T-SQL) translation: trigger
// transition tables, identity sequence options, covering / partial
// indexes, domains and GET DIAGNOSTICS.

func TestWriteCreateTrigger_TransitionTables(t *testing.T) {
	cases := []struct {
		name     string
		trg      CreateTrigger
		wantLine string
	}{
		{
			name: "insert or update, both tables",
			trg: CreateTrigger{Name: "trg", Timing: "AFTER", Events: []string{"INSERT", "UPDATE"},
				Schema: "sales", Table: "orders", FnName: "trg_fn", ForEach: "STATEMENT",
				NewTable: "inserted", OldTable: "deleted"},
			wantLine: "CREATE TRIGGER \"trg\" AFTER INSERT OR UPDATE ON \"sales\".\"orders\"\n" +
				"  REFERENCING NEW TABLE AS \"inserted\" OLD TABLE AS \"deleted\"\n" +
				"  FOR EACH STATEMENT EXECUTE FUNCTION \"sales\".\"trg_fn\"();\n",
		},
		{
			name: "insert only, new table only",
			trg: CreateTrigger{Name: "trg", Timing: "AFTER", Events: []string{"INSERT"},
				Schema: "dbo", Table: "t", FnName: "f", ForEach: "STATEMENT", NewTable: "inserted"},
			wantLine: "  REFERENCING NEW TABLE AS \"inserted\"\n  FOR EACH STATEMENT",
		},
		{
			name: "delete only, old table only",
			trg: CreateTrigger{Name: "trg", Timing: "AFTER", Events: []string{"DELETE"},
				Schema: "dbo", Table: "t", FnName: "f", ForEach: "STATEMENT", OldTable: "deleted"},
			wantLine: "  REFERENCING OLD TABLE AS \"deleted\"\n  FOR EACH STATEMENT",
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			trg := c.trg
			require.Contains(t, Write([]Stmt{&trg}), c.wantLine)
		})
	}

	// No transition table: the historical two-line form is unchanged.
	out := Write([]Stmt{&CreateTrigger{Name: "trg", Timing: "BEFORE", Event: "INSERT",
		Schema: "mig", Table: "t", FnName: "f"}})
	require.Contains(t, out, "CREATE TRIGGER \"trg\" BEFORE INSERT ON \"mig\".\"t\"\n  FOR EACH ROW EXECUTE FUNCTION \"mig\".\"f\"();\n")
	require.NotContains(t, out, "REFERENCING")
}

func TestWriteCreateTable_IdentityOptions(t *testing.T) {
	out := Write([]Stmt{&CreateTable{Schema: "dbo", Name: "t", Columns: []ColumnDef{
		{Name: "id", Type: "integer", NotNull: true, Identity: IdentityByDefault,
			HasIdentityOptions: true, IdentityStart: 100, IdentityIncrement: -5},
		{Name: "n", Type: "bigint", Identity: IdentityByDefault},
	}}})
	require.Contains(t, out, `"id" integer GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY -5) NOT NULL`)
	require.Contains(t, out, "  \"n\" bigint GENERATED BY DEFAULT AS IDENTITY\n")
	require.NotContains(t, out, `IDENTITY (START WITH 1 INCREMENT BY 1)`)

	out = Write([]Stmt{&CreateTable{Schema: "dbo", Name: "t", Columns: []ColumnDef{
		{Name: "a", Type: "integer", Identity: IdentityByDefault, HasIdentityOptions: true,
			IdentityStart: -10, IdentityIncrement: 1, HasIdentityMin: true, IdentityMin: -10},
		{Name: "b", Type: "integer", Identity: IdentityByDefault, HasIdentityOptions: true,
			IdentityStart: 0, IdentityIncrement: -1, HasIdentityMax: true, IdentityMax: 0},
	}}})
	require.Contains(t, out, `"a" integer GENERATED BY DEFAULT AS IDENTITY (START WITH -10 INCREMENT BY 1 MINVALUE -10),`)
	require.Contains(t, out, `"b" integer GENERATED BY DEFAULT AS IDENTITY (START WITH 0 INCREMENT BY -1 MAXVALUE 0)`)
}

func TestWriteCreateTable_NamedPrimaryKey(t *testing.T) {
	out := Write([]Stmt{&CreateTable{Schema: "dbo", Name: "t", PrimaryKey: []string{"id"}, PrimaryKeyName: "pk_t",
		Columns: []ColumnDef{{Name: "id", Type: "integer", NotNull: true}}}})
	require.Contains(t, out, "  CONSTRAINT \"pk_t\" PRIMARY KEY (\"id\")\n")
	out = Write([]Stmt{&CreateTable{Schema: "dbo", Name: "t", PrimaryKey: []string{"id"},
		Columns: []ColumnDef{{Name: "id", Type: "integer", NotNull: true}}}})
	require.Contains(t, out, "  PRIMARY KEY (\"id\")\n")
}

func TestWriteCreateIndex_IncludeAndWhere(t *testing.T) {
	out := Write([]Stmt{&CreateIndex{Schema: "sales", Table: "order details", Name: "ix",
		Columns: []string{"productid"}, Include: []string{"qty", "Note"}, Where: `"qty" > 10`}})
	require.Equal(t, `CREATE INDEX "ix" ON "sales"."order details" ("productid") INCLUDE ("qty","Note") WHERE ("qty" > 10);`+"\n", out)

	// Plain index: byte-identical to the historical output.
	out = Write([]Stmt{&CreateIndex{Schema: "mig", Table: "t", Name: "ix", Unique: true, Columns: []string{"a"}}})
	require.Equal(t, `CREATE UNIQUE INDEX "ix" ON "mig"."t" ("a");`+"\n", out)
}

func TestWriteCreateDomain(t *testing.T) {
	require.Equal(t, `CREATE DOMAIN "dbo"."name" AS varchar(50);`+"\n",
		Write([]Stmt{&CreateDomain{Schema: "dbo", Name: "name", Type: "varchar(50)"}}))
	require.Equal(t, `CREATE DOMAIN "dbo"."flag" AS boolean NOT NULL DEFAULT false CHECK (VALUE IS NOT NULL);`+"\n",
		Write([]Stmt{&CreateDomain{Schema: "dbo", Name: "flag", Type: "boolean", NotNull: true,
			Default: "false", Checks: []string{"VALUE IS NOT NULL"}}}))
}

func TestWritePLGetDiagnostics(t *testing.T) {
	out := WritePLpgSQL(&PLBlock{Body: []PLStmt{
		&PLRawSQL{Text: "UPDATE t SET a = 1"},
		&PLGetDiagnostics{Target: "_rowcount"},
		&PLGetDiagnostics{Target: "n", Item: "PG_CONTEXT"},
	}})
	require.Contains(t, out, "  GET DIAGNOSTICS _rowcount = ROW_COUNT;\n")
	require.Contains(t, out, "  GET DIAGNOSTICS n = PG_CONTEXT;\n")
}
